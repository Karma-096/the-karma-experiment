CREATE TABLE IF NOT EXISTS karma_internal.crypto_providers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_id text REFERENCES karma_internal.crypto_assets(asset_id) ON DELETE CASCADE,
  purpose text NOT NULL CHECK (purpose IN ('discovery','verification','price')),
  operator text NOT NULL CHECK (length(btrim(operator)) BETWEEN 2 AND 80),
  kind text NOT NULL CHECK (length(btrim(kind)) BETWEEN 2 AND 40),
  base_url text NOT NULL CHECK (base_url ~ '^https://'),
  enabled boolean NOT NULL DEFAULT true,
  configuration jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(configuration)='object'),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
