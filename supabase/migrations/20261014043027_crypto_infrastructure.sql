CREATE TABLE IF NOT EXISTS karma_internal.crypto_settings (
  singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
  scanner_enabled boolean NOT NULL DEFAULT false,
  payments_enabled boolean NOT NULL DEFAULT false,
  project_url text,
  scan_interval_minutes integer NOT NULL DEFAULT 15 CHECK (scan_interval_minutes BETWEEN 5 AND 1440),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  CHECK (project_url IS NULL OR project_url ~ '^https://[a-z0-9-]+\.supabase\.co$'),
  CHECK (NOT payments_enabled OR scanner_enabled)
);

INSERT INTO karma_internal.crypto_settings(singleton) VALUES(true)
ON CONFLICT (singleton) DO NOTHING;

