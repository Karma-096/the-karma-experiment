CREATE TABLE IF NOT EXISTS karma_internal.crypto_checkpoints (
  asset_id text PRIMARY KEY REFERENCES karma_internal.crypto_assets(asset_id) ON DELETE CASCADE,
  last_scanned_height bigint CHECK (last_scanned_height IS NULL OR last_scanned_height >= 0),
  last_scanned_hash text,
  last_finalized_height bigint CHECK (last_finalized_height IS NULL OR last_finalized_height >= 0),
  last_success_at timestamptz,
  consecutive_failures integer NOT NULL DEFAULT 0 CHECK (consecutive_failures BETWEEN 0 AND 1000000),
  next_retry_at timestamptz,
  last_error text CHECK (last_error IS NULL OR length(last_error) <= 300),
  state jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(state)='object'),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

INSERT INTO karma_internal.crypto_checkpoints(asset_id)
SELECT asset_id FROM karma_internal.crypto_assets
ON CONFLICT (asset_id) DO NOTHING;

CREATE TABLE IF NOT EXISTS karma_internal.crypto_scan_invocations (
  id uuid PRIMARY KEY DEFAULT extensions.gen_random_uuid(),
  token_hash text NOT NULL UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
  mode text NOT NULL CHECK (mode IN ('scheduled','manual','health_check')),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  expires_at timestamptz NOT NULL,
  claimed_at timestamptz,
  CHECK (expires_at > created_at)
);

CREATE TABLE IF NOT EXISTS karma_internal.crypto_scan_runs (
  id uuid PRIMARY KEY DEFAULT extensions.gen_random_uuid(),
  invocation_id uuid UNIQUE REFERENCES karma_internal.crypto_scan_invocations(id) ON DELETE SET NULL,
  mode text NOT NULL CHECK (mode IN ('scheduled','manual','health_check')),
  status text NOT NULL DEFAULT 'running' CHECK (status IN ('running','skipped','succeeded','partial','failed')),
  started_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  finished_at timestamptz,
  discovered_count integer NOT NULL DEFAULT 0 CHECK (discovered_count >= 0),
  verified_count integer NOT NULL DEFAULT 0 CHECK (verified_count >= 0),
  valued_count integer NOT NULL DEFAULT 0 CHECK (valued_count >= 0),
  safe_error text CHECK (safe_error IS NULL OR length(safe_error) <= 300),
  details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details)='object')
);

CREATE TABLE IF NOT EXISTS karma_internal.crypto_observations (
  id uuid PRIMARY KEY DEFAULT extensions.gen_random_uuid(),
  asset_id text NOT NULL REFERENCES karma_internal.crypto_assets(asset_id),
  network text NOT NULL,
  transaction_hash text NOT NULL CHECK (length(transaction_hash) BETWEEN 32 AND 128),
  amount_atomic numeric(78,0) NOT NULL CHECK (amount_atomic > 0),
  amount numeric NOT NULL CHECK (amount > 0),
  decimals smallint NOT NULL CHECK (decimals BETWEEN 0 AND 30),
  block_height bigint CHECK (block_height IS NULL OR block_height >= 0),
  block_hash text,
  observed_at timestamptz,
  confirmations integer NOT NULL DEFAULT 0 CHECK (confirmations >= 0),
  status text NOT NULL CHECK (status IN ('pending','confirmed','failed','reorged','needs_review')),
  canonical boolean NOT NULL DEFAULT false,
  provider_evidence jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(provider_evidence)='array'),
  valuation_status text NOT NULL DEFAULT 'pending' CHECK (valuation_status IN ('pending','valued','unavailable','disputed')),
  price_usd numeric CHECK (price_usd IS NULL OR price_usd > 0),
  amount_usd numeric CHECK (amount_usd IS NULL OR amount_usd > 0),
  valuation_sources jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(valuation_sources)='array'),
  valued_at timestamptz,
  contribution_id uuid UNIQUE REFERENCES public.karma_contributions(id) ON DELETE SET NULL,
  first_seen_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  last_checked_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  revoked_at timestamptz,
  revocation_reason text CHECK (revocation_reason IS NULL OR length(revocation_reason) <= 120),
  UNIQUE (asset_id,transaction_hash),
  CHECK ((valuation_status='valued') = (price_usd IS NOT NULL AND amount_usd IS NOT NULL AND valued_at IS NOT NULL)),
  CHECK (pg_column_size(provider_evidence) <= 65536),
  CHECK (pg_column_size(valuation_sources) <= 32768)
);

